"""Display Query transport cannot become a writer or a second numeric authority."""

import ast
from pathlib import Path

ROOT = Path(__file__).parents[2]


def test_chart_query_contains_no_plugin_store_or_scientific_command_imports():
    paths = [
        ROOT / "src/onlyalpha/application/chart_study_product_query.py",
        *(ROOT / "packages/onlyalpha-http-server/src/onlyalpha_http_server/chart_studies").glob("*.py"),
    ]
    forbidden = (
        "onlyalpha_plugin_",
        "onlyalpha.persistence",
        "onlyalpha.research.executor",
        "onlyalpha.research.command",
        "onlyalpha.runtime.work",
    )
    for path in paths:
        tree = ast.parse(path.read_text())
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom):
                assert not (node.module or "").startswith(forbidden)
        assert "acquire_bars(" not in path.read_text()


def test_chart_transport_imports_only_its_read_only_product_boundary():
    # The exact ADR 0138 exception admits only the owning Query and its errors,
    # not arbitrary application constructors or business mutation authority.
    path = ROOT / "packages/onlyalpha-http-server/src/onlyalpha_http_server/chart_studies/routes.py"
    admitted = {
        "onlyalpha.application.chart_study_product_query": {
            "OnlyChartStudyProductQueryService",
            "OnlyChartStudyQueryError",
        },
        "onlyalpha.application.source_read_access": {"OnlySourceReadAccessError"},
    }
    for node in ast.walk(ast.parse(path.read_text())):
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("onlyalpha.application"):
            assert node.module in admitted
            assert {alias.name for alias in node.names} <= admitted[node.module]
    assert not any(
        token in path.read_text()
        for token in ("acquire_bars", ".dispatch(", "OnlyCreate", "OnlyPublish", "OnlyResearchCommand")
    )


def test_chart_dto_is_the_only_schema_and_existing_generator_owns_both_consumers():
    source = (ROOT / "scripts/market_data_http_contract.py").read_text()
    assert "ChartStudyEvaluateRequestDto" in source and "model.model_json_schema()" in source
    assert "src/api/chartStudies/http.generated.ts" in source
    projection = (ROOT / "packages/onlyalpha-web-console/src/api/chartStudies/http.generated.ts").read_text()
    assert projection.startswith("// Generated by scripts/market_data_http_contract.py")
    assert 'satisfies z.ZodType<components["schemas"]["ChartStudyEvaluateDto"]>' in projection
