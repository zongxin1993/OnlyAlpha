"""Project the server's Market Data bars DTO to the browser validator."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from typing import Any

from market_data_stream_contract import _definitions, _expression
from onlyalpha_http_server.chart_studies.schema import (
    ChartStudyCapabilitiesDto,
    ChartStudyErrorEnvelopeDto,
    ChartStudyEvaluateDto,
    ChartStudyEvaluateRequestDto,
)
from onlyalpha_http_server.market_data.schema import MarketDataBarWindowDto

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "packages/onlyalpha-web-console/src/api/marketData/http.generated.ts"
CHART_WEB = ROOT / "packages/onlyalpha-web-console/src/api/chartStudies/http.generated.ts"


def render() -> str:
    document = MarketDataBarWindowDto.model_json_schema()
    lines = [
        "// Generated by scripts/market_data_http_contract.py; do not edit.",
        'import { z } from "zod";',
        "",
    ]
    for name, schema in _definitions(document):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    lines += [
        f"export const marketDataBarsSchema = {_expression(document)}.refine(value => {{",
        '    const complete = value.coverage.status === "COMPLETE";',
        '    const derived = value.resolution_mode === "DERIVED";',
        "    return (value.bars.length > 0) === complete &&",
        "        (!complete || value.revision_evidence.length > 0) &&",
        "        (value.history_projection_fingerprint !== null) === complete &&",
        "        (value.resume_after_sequence !== null) === complete &&",
        "        (value.resume_plan_fingerprint !== null) === complete &&",
        "        (value.derived_projection_fingerprint !== null) === (complete && derived);",
        "});",
        "export type MarketDataBars = z.infer<typeof marketDataBarsSchema>;",
        "",
    ]
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(WEB)],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def render_chart() -> str:
    roots = {
        name: model.model_json_schema()
        for name, model in (
            ("ChartStudyCapabilities", ChartStudyCapabilitiesDto),
            ("ChartStudyEvaluateRequest", ChartStudyEvaluateRequestDto),
            ("ChartStudyEvaluate", ChartStudyEvaluateDto),
            ("ChartStudyErrorEnvelope", ChartStudyErrorEnvelopeDto),
        )
    }
    definitions: dict[str, Any] = {}
    for document in roots.values():
        for name, schema in document.pop("$defs").items():
            if name in definitions and definitions[name] != schema:
                raise ValueError("Chart Query definition collision")
            definitions[name] = schema
    lines = [
        "// Generated by scripts/market_data_http_contract.py; do not edit.",
        'import { z } from "zod";',
        'import type { components } from "../research/generated";',
        "",
    ]
    for name, schema in _definitions({"$defs": definitions}):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    for name, document in roots.items():
        lines += [
            f'export const {name}Schema = {_expression(document)} satisfies z.ZodType<components["schemas"]["{name}Dto"]>;',
            f"export type {name} = z.infer<typeof {name}Schema>;",
        ]
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(CHART_WEB)],
        input="\n".join(lines) + "\n",
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> None:
    projections = ((WEB, render()), (CHART_WEB, render_chart()))
    if sys.argv[1:] == ["write"]:
        for path, rendered in projections:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered, encoding="utf-8")
    elif sys.argv[1:] == ["check"]:
        for path, rendered in projections:
            if path.read_text(encoding="utf-8") != rendered:
                raise SystemExit("HTTP contract projection is stale; run scripts/market_data_http_contract.py write")
    else:
        raise SystemExit("usage: market_data_http_contract.py write|check")


if __name__ == "__main__":
    main()
