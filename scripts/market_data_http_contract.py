def render_chart() -> str:
    roots = {
        name: schema_document(exported("openapi"), name + "Dto")
        for name in (
            "ChartStudyCapabilities",
            "ChartStudyEvaluateRequest",
            "ChartStudyEvaluate",
            "TemporaryChartStudyEvaluateRequest",
            "TemporaryChartStudyEvaluate",
            "TemporaryChartStudyBatchRequest",
            "TemporaryChartStudyBatch",
        )
    }
    definitions: dict[str, Any] = {}
    for document in roots.values():
        for name, schema in document.pop("$defs").items():
            if name in definitions and definitions[name] != schema:
                raise ValueError("Chart Query definition collision")
            definitions[name] = schema
    lines = [
        "// Generated by scripts/market_data_http_contract.py; do not edit.",
        'import { z } from "zod";',
        'import type { components } from "../research/generated";',
        "",
    ]
    for name, schema in _definitions({"$defs": definitions}):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    for name, document in roots.items():
        lines += [
            f'export const {name}Schema = {_expression(document)} satisfies z.ZodType<components["schemas"]["{name}Dto"]>;',
            f"export type {name} = z.infer<typeof {name}Schema>;",
        ]
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(CHART_WEB)],
        input="\n".join(lines) + "\n",
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def render_errors() -> str:
    document = schema_document(exported("openapi"), "NativeErrorEnvelope")
    lines = ["// Generated by scripts/market_data_http_contract.py; do not edit.", 'import { z } from "zod";']
    for name, schema in _definitions(document):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    lines.append(f"export const nativeErrorSchema = {_expression(document)};")
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(ERROR_WEB)],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> None:
    from scripts.workspace_http_contract import TARGET as WORKSPACE_WEB
    from scripts.workspace_http_contract import render as render_workspace

    projections = (
        (WORKSPACE_WEB, render_workspace()),
        (WEB, render()),
        (CHART_WEB, render_chart()),
        (ERROR_WEB, render_errors()),
        (TEMPORARY_WEB, render_temporary()),
    )
    if sys.argv[1:] == ["write"]:
        for path, rendered in projections:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered, encoding="utf-8")
    elif sys.argv[1:] == ["check"]:
        for path, rendered in projections:
            if path.read_text(encoding="utf-8") != rendered:
                raise SystemExit("HTTP contract projection is stale; run scripts/market_data_http_contract.py write")
    else:
        raise SystemExit("usage: market_data_http_contract.py write|check")


if __name__ == "__main__":
    main()
