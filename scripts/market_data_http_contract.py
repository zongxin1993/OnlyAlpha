"""Project the server's Market Data bars DTO to the browser validator."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.market_data_stream_contract import _definitions, _expression
from scripts.native_http_contract import exported, schema_document

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "packages/onlyalpha-web-console/src/api/marketData/http.generated.ts"
CHART_WEB = ROOT / "packages/onlyalpha-web-console/src/api/chartStudies/http.generated.ts"
ERROR_WEB = ROOT / "packages/onlyalpha-web-console/src/api/errors.generated.ts"
TEMPORARY_WEB = ROOT / "packages/onlyalpha-web-console/src/api/marketData/temporary.generated.ts"


def render() -> str:
    document = schema_document(exported("openapi"), "MarketDataBarWindowDto")
    lines = [
        "// Generated by scripts/market_data_http_contract.py; do not edit.",
        'import { z } from "zod";',
        "",
    ]
    for name, schema in _definitions(document):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    lines += [
        f"export const marketDataBarsSchema = {_expression(document)}.refine(value => {{",
        '    const complete = value.coverage.status === "COMPLETE";',
        '    const derived = value.resolution_mode === "DERIVED";',
        "    return (value.bars.length > 0) === complete &&",
        "        (!complete || value.revision_evidence.length > 0) &&",
        "        (value.history_projection_fingerprint !== null) === complete &&",
        "        (value.resume_after_sequence !== null) === complete &&",
        "        (value.resume_plan_fingerprint !== null) === complete &&",
        "        (value.derived_projection_fingerprint !== null) === (complete && derived);",
        "});",
        "export type MarketDataBars = z.infer<typeof marketDataBarsSchema>;",
        "",
    ]
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(WEB)],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout


