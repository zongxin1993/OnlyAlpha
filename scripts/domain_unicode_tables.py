"""Reproduce the Unicode 15 lexical tables of the pinned Python Domain runtime.

These are immutable lexical data, not a second implementation of numerical math.
Run --check in validation; no table is generated during builds or tests.
"""

from __future__ import annotations

import argparse
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "crates/onlyalpha-kernel/domain/src/unicode_data.rs"


def render() -> str:
    if unicodedata.unidata_version != "15.0.0":
        raise ValueError("DOMAIN_UNICODE_VERSION_MISMATCH")
    ranges: list[tuple[int, int]] = []
    digits: list[tuple[int, int]] = []
    uppercase: list[tuple[int, str]] = []
    for point in range(0x110000):
        char = chr(point)
        if char.upper() != char:
            uppercase.append((point, char.upper()))
        if char.isalnum():
            if ranges and ranges[-1][1] == point - 1:
                ranges[-1] = ranges[-1][0], point
            else:
                ranges.append((point, point))
        if unicodedata.category(char) == "Nd" and unicodedata.decimal(char) == 0:
            digits.append((point, point + 9))

    def table(name: str, items: list[tuple[int, int]]) -> str:
        return (
            f"pub(crate) const {name}: &[(u32, u32)] = &[\n"
            + "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in items)
            + "];\n"
        )

    uppercase_table = "#[rustfmt::skip]\npub(crate) const UPPERCASE: &[(u32, &str)] = &[\n"
    for point, replacement in uppercase:
        literal = "".join(f"\\u{{{ord(char):X}}}" for char in replacement)
        uppercase_table += f'    (0x{point:X}, "{literal}"),\n'
    uppercase_table += "];\n"
    return (
        "// Unicode 15.0.0 lexical data; generated by scripts/domain_unicode_tables.py.\n"
        + table("ALPHANUMERIC", ranges)
        + table("DECIMAL_DIGITS", digits)
        + uppercase_table
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if TARGET.read_text() != text:
            raise ValueError("DOMAIN_UNICODE_TABLE_MISMATCH")
    else:
        TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
