"""Mechanical browser validator projection of the owning native workspace DTO."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.market_data_stream_contract import _definitions, _expression
from scripts.native_http_contract import exported, schema_document

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "packages/onlyalpha-web-console/src/api/workspace/http.generated.ts"


def render() -> str:
    document = schema_document(exported("openapi"), "WorkspaceBookDto")
    lines = ["// Generated by scripts/workspace_http_contract.py; do not edit.", 'import { z } from "zod";', ""]
    for name, schema in _definitions(document):
        lines.append(f"const {name}Schema = {_expression(schema)};")
    lines += [
        f"export const workspaceBookSchema = {_expression(document)}.refine(value => Number.isSafeInteger(value.version) && ((value.version === 0) === (value.configuration === null)));",
        "export type WorkspaceBook = z.infer<typeof workspaceBookSchema>;",
        'export type WorkspaceConfiguration = NonNullable<WorkspaceBook["configuration"]>;',
        'export type WorkspaceStudy = WorkspaceConfiguration["studies"][number];',
        "",
    ]
    return subprocess.run(
        [str(ROOT / "packages/onlyalpha-web-console/node_modules/.bin/prettier"), "--stdin-filepath", str(TARGET)],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout
