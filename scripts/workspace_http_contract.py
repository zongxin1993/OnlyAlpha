"""Mechanical browser validator projection of the owning native workspace DTO."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.market_data_stream_contract import _definitions, _expression
from scripts.native_http_contract import exported, schema_document

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "packages/frontend/src/api/workspace/http.generated.ts"


def render() -> str:
    document = schema_document(exported("openapi"), "WorkspaceBookDto")
    lines = ["// Generated by scripts/workspace_http_contract.py; do not edit.", 'import { z } from "zod";', ""]
    for name, schema in _definitions(document):
        expression = _expression(schema)
        if name == "NamedWorkspaceDto":
            # JSON Schema/Rust count Unicode scalar values; Zod length counts UTF-16 units.
            field = schema["properties"]["name"]
            scalar_name = f"z.string().refine(value => Array.from(value).length >= {field['minLength']} && Array.from(value).length <= {field['maxLength']} && value.trim() === value && !/\\p{{Cc}}/u.test(value))"
            expression = expression.replace(_expression(field), scalar_name)
        lines.append(f"const {name}Schema = {expression};")
    lines += [
        f"export const workspaceBookSchema = {_expression(document)}.refine(value => Number.isSafeInteger(value.version) && ((value.version === 0) === (value.workspaces.length === 0)) && new Set(value.workspaces.map(item => item.workspace_id)).size === value.workspaces.length && (value.workspaces.length === 0 ? value.active_workspace_id === null : value.workspaces.some(item => item.workspace_id === value.active_workspace_id)));",
        "export type WorkspaceBook = z.infer<typeof workspaceBookSchema>;",
        'export type WorkspaceConfiguration = WorkspaceBook["workspaces"][number]["configuration"];',
        'export type WorkspaceStudy = WorkspaceConfiguration["studies"][number];',
        "",
    ]
    return subprocess.run(
        [str(ROOT / "packages/frontend/node_modules/.bin/prettier"), "--stdin-filepath", str(TARGET)],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout
